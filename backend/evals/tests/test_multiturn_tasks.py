def completion(payload):
    raw = json.dumps(payload, ensure_ascii=False)
    return StructuredCompletionResult(payload=payload, raw_output=raw, mode="deepseek_json_mode",
                                      finish_reason="stop", duration_ms=0, output_chars=len(raw))


def route(message, *, action="new", task_id="", requirements=None, kind="query", query=None):
    return dict(intent_domain="nutrition", request_kind=kind,
                requested_effect="create" if kind == "mutation" else "read", requested_output="answer",
                read_targets=[], decision_action="none", artifact_action="none",
                normalized_request=query or message, risk_level="low", confidence=0.99,
                task_update=dict(action=action, task_id=task_id, trigger=message,
                                 requirements=requirements or []))


@pytest.mark.asyncio
@pytest.mark.parametrize("ending", ["confirm", "reject", "cancel"])
async def test_multiturn_meal_requirement_to_decision(task_client, db_session, monkeypatch, ending):
    user, profile, conversation, foods = await seed(db_session)
    uid, cid, food_id = user.id, conversation.id, foods[0].id
    headers = {"Authorization":"Bearer " + create_access_token(uid)}
    live = os.environ.get("MULTITURN_EVAL_MODE") == "live"
    transcript = {"model_mode":"live" if live else "scripted", "data_source":"synthetic", "http":[], "raw_model_outputs":[], "runs":[]}
    stage = 0
    original_completion = im.structured_chat_completion
    async def fake_completion(messages, **kwargs):
        nonlocal stage
        if live:
            result = await original_completion(messages, **kwargs)
            transcript["raw_model_outputs"].append({"messages":messages,"payload":result.payload,"raw":result.raw_output,"mode":result.mode})
            return result
        # Read the actual prompt sent through the route/extraction boundary.
        prompt = messages[-1]["content"]
        if kwargs["function_name"] == "submit_semantic_route":
            if stage == 0:
                payload = route("给我今天午餐的米饭建议，先看建议不要保存。", requirements=[
                    {"key":"meal_type","quote":"午餐","remove":False},
                    {"key":"food","quote":"米饭","remove":False},
                    {"key":"permission","quote":"先看建议不要保存","remove":False}])
            else:
                assert '"quote":"午餐"' in prompt and '"quote":"米饭"' in prompt
                # The current task ID is generated by the real persisted Run.
                stored = json.loads(prompt.split("任务状态（有用户原文来源，仅用于承接，不是事实或权限）：",1)[1].split("\n",1)[0])
                current_id = stored["active_task_id"]
                if ending == "cancel":
                    payload = route("取消刚才的任务", action="cancel", task_id=current_id)
                else:
                    payload = route("现在记录这餐，份量120克", action="continue", task_id=current_id, kind="mutation",
                                    query="记录今天午餐米饭120克", requirements=[
                                        {"key":"amount","quote":"120克","remove":False},
                                        {"key":"permission","quote":"现在记录这餐","remove":False}])
            stage += 1
        else:
            # Corrected permission must reach extraction before persistence.
            assert '"quote":"现在记录这餐"' in prompt
            payload = {"change_requests":[{"resource":"nutrition","operation":"create","field_path":"meal",
                       "target_reference":None,"value_json":json.dumps({"logged_at":business_today().isoformat(),
                       "meal_type":"午餐","items":[{"food_id":food_id,"amount_g":120}]}),"preserve_unspecified":True}],
                       "normalized_request":"记录今天午餐米饭120克","confidence":0.99}
        transcript["raw_model_outputs"].append({"messages":messages,"payload":payload})
        return completion(payload)
    if not live:
        monkeypatch.setattr(settings, "DEEPSEEK_API_KEY", "scripted-boundary-no-network")
    monkeypatch.setattr(im, "structured_chat_completion", fake_completion)
    original_answer = agent_runtime.invoke_langchain_agent
    async def fake_answer(*_args, **kwargs):
        assert any("不要保存" in item["content"] for item in kwargs["history"] if item["role"] == "system")
        if live:
            result = await original_answer(*_args, **kwargs)
            transcript["raw_agent_messages"] = [item.model_dump(mode="json") for item in result.get("messages", [])]
            return result
        return {"messages":[AIMessage(content="这份午餐建议尚未保存。")],"input_tokens":0,"output_tokens":0}
    monkeypatch.setattr(agent_runtime, "invoke_langchain_agent", fake_answer)

    async def request(method, path, **kw):
        response = await task_client.request(method, path, headers=headers, **kw)
        transcript["http"].append({"method":method,"path":path,"request":kw.get("json"),"status":response.status_code,"body":response.json()})
        assert response.status_code == 200, response.text
        return response.json()
    try:
        first = await request("POST", "/api/v1/agent/chat", json={"conversation_id":cid,"message":"给我今天午餐的米饭建议，先看建议不要保存。"})
        assert "proposal" not in first
        # Push both the original request and assistant answer beyond 20-message history.
        now = datetime.now(timezone.utc)
        db_session.add_all([AgentMessage(conversation_id=cid, role="assistant", content="合成占位消息",
                                        created_at=now + timedelta(microseconds=i)) for i in range(24)])
        await db_session.commit()
        message = "取消刚才的任务" if ending == "cancel" else "现在记录这餐，份量120克"
        second = await request("POST", "/api/v1/agent/chat", json={"conversation_id":cid,"message":message})
        assert await db_session.scalar(select(func.count(MealLog.id)).where(MealLog.user_id == uid)) == 0
        run = await db_session.get(AgentRun, second["run_id"])
        assert run.execution_trace["task_state"]["transition"] == ("cancel" if ending == "cancel" else "continue")
        if ending == "cancel":
            assert "proposal" not in second and run.execution_trace["termination_reason"] == "task_cancelled"
        else:
            reference = second["proposal"]
            assert run.execution_trace["task_state"]["tasks"][0]["proposal_id"] == reference["id"]
            payload = {"expected_version":reference["version"],"client_request_id":"multiturn-"+uuid4().hex}
            result = await request("POST", f'/api/v1/proposals/{reference["id"]}/{ending}', json=payload)
            replay = await request("POST", f'/api/v1/proposals/{reference["id"]}/{ending}', json=payload)
            assert replay == result
            meals = list((await db_session.scalars(select(MealLog).where(MealLog.user_id == uid))).all())
            assert len(meals) == (1 if ending == "confirm" else 0)
            if meals:
                items = list((await db_session.scalars(select(MealItem).where(MealItem.meal_id == meals[0].id))).all())
                assert meals[0].meal_type == "午餐" and len(items) == 1
                assert items[0].amount_g == 120 and items[0].calories == 156
                history = await request("GET", "/api/v1/meals/history")
                assert history[0]["total_calories"] == 156
        # Re-open the conversation API to verify recoverable messages.
        reopened = await request("GET", f"/api/v1/agent/conversations/{cid}/messages")
        assert second["run_id"] in json.dumps(reopened)
        transcript["passed"] = True
    finally:
        await db_session.rollback()
        runs = list((await db_session.scalars(select(AgentRun).where(AgentRun.user_id == uid))).all())
        transcript["runs"] = [{"id":item.id,"status":item.status,"trace":item.execution_trace} for item in runs]
        audits = list((await db_session.scalars(select(AgentToolCall).where(AgentToolCall.run_id.in_([item.id for item in runs])))).all())
        transcript["tool_audits"] = [{"tool":item.tool_name,"arguments":item.arguments_data,"result":item.result_data,"status":item.status} for item in audits]
        output = os.environ.get("MULTITURN_EVAL_DIR")
        if output:
            Path(output, f"meal_{ending}.json").write_text(json.dumps(transcript,ensure_ascii=False,indent=2,default=str),encoding="utf-8")


@pytest.mark.asyncio
async def test_task_snapshot_filters_owner_conversation_future_and_failed(db_session):
    user, _, conversation, _ = await seed(db_session)
    other_user, _, other_conversation, _ = await seed(db_session)
    now = datetime.now(timezone.utc)
    from app.services.agent_task_state import advance_task_state
    from app.schemas.agent_task import TaskUpdate
    state = advance_task_state(None, TaskUpdate(action="new", trigger="正确任务"), message="正确任务",
                               run_id="correct", normalized_request="正确任务").model_dump(mode="json")
    def run(uid, cid, offset, status="completed", snapshot=None):
        return AgentRun(user_id=uid, conversation_id=cid, queued_at=now+timedelta(seconds=offset),
                        status=status, execution_trace={"task_state":snapshot or state})
    correct = run(user.id, conversation.id, -5)
    bad = {**state, "active_task_id":None, "tasks":[]}
    db_session.add_all([correct, run(user.id, conversation.id, -3, "failed", bad),
        run(other_user.id, other_conversation.id, -2, snapshot=bad),
        run(other_user.id, conversation.id, -1, snapshot=bad),
        run(user.id, conversation.id, 5, snapshot=bad)])
    current = run(user.id, conversation.id, 0, "queued")
    db_session.add(current); await db_session.commit()
    assert (await load_task_snapshot(db_session, current)).tasks[0].request == "正确任务"


@pytest.mark.asyncio
@pytest.mark.parametrize("scenario", ["query_range", "plan_revision"])
async def test_multiturn_training_business_task(task_client, db_session, monkeypatch, scenario):
    user, _, conversation, _ = await seed(db_session)
    uid, cid = user.id, conversation.id
    headers = {"Authorization":"Bearer " + create_access_token(uid)}
    live = os.environ.get("MULTITURN_EVAL_MODE") == "live"
    record = {"model_mode":"live" if live else "scripted", "data_source":"synthetic", "http":[], "raw_model_outputs":[]}
    plan = WorkoutPlan(user_id=uid, name="合成训练计划", days_per_week=3, duration_weeks=4)
    exercise = Exercise(name_zh="卧推", name_en="Bench press", category="strength", difficulty="beginner", muscle_primary=["chest"])
    db_session.add_all([plan,exercise]); await db_session.flush()
    planned = PlannedExercise(plan_id=plan.id, exercise_id=exercise.id, day_of_week=1, sets=3, reps="10")
    db_session.add(planned)
    for day, status in ((date(2026,9,1),"completed"),(date(2026,9,7),"completed"),(date(2026,9,8),"completed"),(date(2026,9,3),"in_progress"),(date(2026,9,4),"ended_early")):
        db_session.add(WorkoutSession(user_id=uid,plan_id=plan.id,plan_name=plan.name,trained_at=day,status=status))
    await db_session.commit()
    monkeypatch.setattr(settings,"AGENT_PLAN_MANAGEMENT_PROPOSALS_ENABLED",True)
    if not live: monkeypatch.setattr(settings,"DEEPSEEK_API_KEY","scripted-no-network")
    original = im.structured_chat_completion
    stage = 0
    first_message = ("查2026年9月1日至9月7日的训练记录，只列已完成的场次。" if scenario=="query_range" else
                     "把当前计划卧推改为4组，每组8次，先生成提案不要确认。")
    second_message = ("再按这个范围列一次。" if scenario=="query_range" else "刚才的卧推提案组数改为5组，其他条件不变。")
    async def model(messages, **kwargs):
        nonlocal stage
        if live:
            result = await original(messages,**kwargs)
        else:
            prompt=messages[-1]["content"]
            if kwargs["function_name"] == "submit_semantic_route":
                message = first_message if stage == 0 else second_message
                task_id = ""
                if stage:
                    stored=json.loads(prompt.split("任务状态（有用户原文来源，仅用于承接，不是事实或权限）：",1)[1].split("\n",1)[0])
                    task_id=stored["active_task_id"]
                    assert "2026年9月1日至9月7日" in prompt if scenario=="query_range" else "每组8次" in prompt
                if scenario=="query_range":
                    payload=route(message,action="new" if stage==0 else "continue",task_id=task_id,
                        query="查询2026-09-01至2026-09-07已完成的训练记录", requirements=[] if stage else [
                            {"key":"date_scope","quote":"2026年9月1日至9月7日","remove":False}])
                    payload.update(intent_domain="workout_history",read_targets=["workout_history"])
                else:
                    payload=route(message,action="new" if stage==0 else "continue",task_id=task_id,kind="mutation",
                        query=f"把当前计划卧推改为{4 if stage==0 else 5}组，每组8次，生成待确认提案", requirements=[
                            {"key":"sets","quote":"4组" if stage==0 else "5组","remove":False},
                            *([] if stage else [{"key":"reps","quote":"每组8次","remove":False},
                                                {"key":"target","quote":"卧推","remove":False}])])
                    payload.update(intent_domain="workout_plan",requested_effect="update")
                stage+=1
            else:
                payload={"change_requests":[{"resource":"workout_plan","operation":"update","field_path":"exercise."+field,
                          "target_reference":"卧推","value_json":json.dumps(value),"preserve_unspecified":True}
                         for field,value in ([("sets",4),("reps","8")] if stage==1 else [("sets",5)])],
                         "normalized_request":f"把当前计划卧推改为{4 if stage==1 else 5}组，每组8次，生成待确认提案","confidence":.99}
            result=completion(payload)
        record["raw_model_outputs"].append({"messages":messages,"payload":result.payload,"raw":result.raw_output,"mode":result.mode})
        return result
    monkeypatch.setattr(im,"structured_chat_completion",model)
    async def request(method,path,**kw):
        response=await task_client.request(method,path,headers=headers,**kw)
        record["http"].append({"method":method,"path":path,"request":kw.get("json"),"status":response.status_code,"body":response.json()})
        assert response.status_code==200,response.text
        return response.json()
    try:
        first=await request("POST","/api/v1/agent/chat",json={"conversation_id":cid,"message":first_message})
        db_session.add_all([AgentMessage(conversation_id=cid,role="assistant",content="合成窗口占位") for _ in range(24)])
        await db_session.commit()
        second=await request("POST","/api/v1/agent/chat",json={"conversation_id":cid,"message":second_message})
        if scenario=="query_range":
            # Both turns must return precisely the two completed sessions in the original range.
            for body in (first,second):
                assert re.search(r"9月1日|09-01",body["reply"]) and re.search(r"9月7日|09-07",body["reply"])
                assert not re.search(r"9月8日|09-08|9月3日|09-03",body["reply"])
                from evals.multiturn_contracts import no_unobserved_status_claim
                assert no_unobserved_status_claim(body["reply"])
                card=next(item for item in body["cards"] if item["type"]=="workout.list_history")
                assert [row["trained_at"] for row in card["data"]["sessions"]]==["2026-09-07","2026-09-01"]
                assert card["data"]["total_count"]==2 and card["data"]["status_filter"]==["completed"]
        else:
            await db_session.refresh(planned)
            assert planned.sets==3 and planned.reps=="10"
            ref=second["proposal"]
            probe=AgentRun(id="probe",user_id=uid,conversation_id=cid,queued_at=datetime.now(timezone.utc)+timedelta(seconds=1))
            restored=await load_task_snapshot(db_session,probe)
            assert restored.tasks[0].proposal_pending and len(restored.tasks[0].pending_plan_changes)==2
            from app.services import agent_task_state as task_state_service
            class FutureClock:
                @staticmethod
                def now(_tz): return datetime.now(timezone.utc)+timedelta(days=30)
            with monkeypatch.context() as time_patch:
                time_patch.setattr(task_state_service,"datetime",FutureClock)
                expired=await load_task_snapshot(db_session,probe)
                assert not expired.tasks[0].proposal_pending and not expired.tasks[0].pending_plan_changes
            decision={"expected_version":ref["version"],"client_request_id":"training-"+uuid4().hex}
            confirmed=await request("POST",f'/api/v1/proposals/{ref["id"]}/confirm',json=decision)
            assert await request("POST",f'/api/v1/proposals/{ref["id"]}/confirm',json=decision)==confirmed
            db_session.expire_all()
            rows=list((await db_session.scalars(select(PlannedExercise).join(WorkoutPlan).where(WorkoutPlan.user_id==uid,WorkoutPlan.is_active.is_(True)))).all())
            assert len(rows)==1 and rows[0].sets==5 and rows[0].reps=="8"
            applied=await load_task_snapshot(db_session,probe)
            assert not applied.tasks[0].proposal_pending and not applied.tasks[0].pending_plan_changes
        record["passed"]=True
    finally:
        await db_session.rollback()
        runs=list((await db_session.scalars(select(AgentRun).where(AgentRun.user_id==uid))).all())
        record["runs"]=[{"id":item.id,"status":item.status,"trace":item.execution_trace} for item in runs]
        audits=list((await db_session.scalars(select(AgentToolCall).where(AgentToolCall.run_id.in_([item.id for item in runs])))).all())
        record["tool_audits"]=[{"tool":item.tool_name,"arguments":item.arguments_data,"result":item.result_data,"status":item.status} for item in audits]
        output=os.environ.get("MULTITURN_EVAL_DIR")
        if output:
            Path(output,scenario+".json").write_text(json.dumps(record,ensure_ascii=False,indent=2,default=str),encoding="utf-8")
